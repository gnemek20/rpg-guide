export function iconFor(material: string | undefined): [string, string] {
  if (!material) return ['lump', 'gray']
  const hit = M[material]
  if (hit) return hit
  const i = material.indexOf('_')
  if (i > 0) {
    const mat = TOOL_MATS[material.slice(0, i)]
    const shape = TOOL_SHAPES[material.slice(i + 1)]
    if (mat && shape) return [shape, mat]
  }
  if (material.endsWith('_PLANKS') || material.endsWith('_LOG')) return ['block', 'wood']
  if (material.endsWith('_ORE')) return ['lump', 'stone']
  if (material.endsWith('_SEEDS')) return ['seeds', 'green']
  for (const [re, hit] of RULES) if (re.test(material)) return hit
  const color = Object.keys(DYES).find((c) => material.startsWith(c + '_'))
  if (/(CONCRETE|WOOL|GLASS|BLOCK|BRICKS|STONE|TERRACOTTA|NYLIUM|ROOTS|STEM|SAND|MUD|MYCELIUM|LIGHT|LANTERN)$/.test(material))
    return ['block', color ? DYES[color] : BLOCK_MAT.find(([re]) => re.test(material))?.[1] ?? 'stone']
  return ['lump', 'gray']
}

