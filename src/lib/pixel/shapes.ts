/** 아이콘 한 장의 색 해석. 글자 -> 색 */
export function colorOf(ch: string, mat: Pal): string | null {
  if (ch === '.') return null
  if (ch === '#') return mat.o
  if (ch === '1') return mat.a
  if (ch === '2') return mat.b
  if (ch === '3') return mat.c
  return FIXED[ch] ?? null
}

export type Seg = { x: number; y: number; w: number; c: string }

/** 가로로 이어진 같은 색 칸을 한 선분으로 묶는다. */
export function segments(shape: string, material: string): Seg[] {
  const rows = SHAPES[shape] ?? SHAPES.lump
  const mat = MATERIALS[material] ?? MATERIALS.gray
  const out: Seg[] = []
  rows.forEach((row, y) => {
    let x = 0
    while (x < 16) {
      const c = colorOf(row[x] ?? '.', mat)
      if (!c) { x++; continue }
      let w = 1
      while (x + w < 16 && colorOf(row[x + w] ?? '.', mat) === c) w++
      out.push({ x, y, w, c })
      x += w
    }
  })
  return out
}

