export function potionMat(name: string): string {
  for (const [re, m] of POTION_WORDS) if (re.test(name)) return m
  let h = 0
  for (const ch of name) h = (h * 31 + ch.charCodeAt(0)) >>> 0
  return POTION_MATS[h % 8]
}

